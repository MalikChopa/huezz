import { describe, expect, it } from 'vitest';
import { generate } from '../../src/palette/generate';
import type { PairReport } from '../../src/palette/roles';
import { HARMONIES, ratioOf, rngOf } from './helpers';

const hex6 = (n: number): string => '#' + Math.floor(n).toString(16).padStart(6, '0').toUpperCase();

describe('typed base', () => {
  it('is the light accent exactly, 1000 random bases x harmonies, whatever the seed', () => {
    const r = rngOf(555);
    let failing = 0;
    for (let i = 0; i < 1000; i++) {
      const base = hex6(r() * 0x1000000);
      const harmony = HARMONIES[Math.floor(r() * HARMONIES.length)] as (typeof HARMONIES)[number];
      const g = generate({ base, harmony, seed: Math.floor(r() * 2 ** 32), locks: 0 });
      expect(g.light.accent).toBe(base);
      const rep = g.report.light.find((x) => x.id === 'accent-fond') as PairReport;
      expect(rep.touchesFixed).toBe(true);
      expect(rep.ok).toBe(ratioOf(base, g.light.fond) >= 4.5);
      if (!rep.ok) failing++;
      // the dark accent is derived, hence free: it must meet 4.5 on the dark fond
      const dark = g.report.dark.find((x) => x.id === 'accent-fond') as PairReport;
      expect(dark.ok).toBe(true);
    }
    console.log(`J2 base: 1000 random bases kept exactly; ${failing} fail accent/fond in light and are reported ok:false`);
    expect(failing).toBeGreaterThan(0);
  });

  it('a base that fails its pair stays untouched and the report says so', () => {
    const g = generate({ base: '#FFEB3B', harmony: 'triad', seed: 1, locks: 0 });
    const rep = g.report.light.find((x) => x.id === 'accent-fond') as PairReport;
    expect(g.light.accent).toBe('#FFEB3B');
    expect(rep.ok).toBe(false);
    expect(rep.ratio).toBeLessThan(2);
    expect(rep.touchesFixed).toBe(true);
    expect(rep.target).toBe(4.5);
  });

  it('accepts #RGB and no-# input (normalised to uppercase #RRGGBB); invalid input falls back to the seed draw', () => {
    expect(generate({ base: '#fa0', harmony: 'triad', seed: 1, locks: 0 }).light.accent).toBe('#FFAA00');
    expect(generate({ base: '0f7c74', harmony: 'triad', seed: 1, locks: 0 }).light.accent).toBe('#0F7C74');
    const drawn = generate({ harmony: 'triad', seed: 1, locks: 0 });
    expect(generate({ base: 'nope', harmony: 'triad', seed: 1, locks: 0 }).light.accent).toBe(drawn.light.accent);
  });

  it('the other roles follow the base hue: free roles regenerated by the seed, all reports consistent', () => {
    const a = generate({ base: '#0F7C74', harmony: 'complementary', seed: 1, locks: 0 });
    const b = generate({ base: '#0F7C74', harmony: 'complementary', seed: 2, locks: 0 });
    expect(a.light.accent).toBe(b.light.accent);
    expect(a.light.fond === b.light.fond && a.light.texte === b.light.texte && a.light.succes === b.light.succes).toBe(false);
    expect(a.report.light.find((x) => x.id === 'accent-fond')?.ok).toBe(true);
  });
});
