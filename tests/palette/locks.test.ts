import { describe, expect, it } from 'vitest';
import { generate, plan } from '../../src/palette/generate';
import { ensure, separate } from '../../src/palette/theme';
import { LOCK_ALL, PAIRS, ROLES, isLocked, type Mode, type PairReport, type Role, type ThemeColors } from '../../src/palette/roles';
import { HARMONIES, bestExtreme, ratioOf, rngOf, seedList } from './helpers';

const MODES: readonly Mode[] = ['light', 'dark'];
type H = (typeof HARMONIES)[number];

function theme(g: ThemeColors): ThemeColors {
  return { light: g.light, dark: g.dark };
}

describe('locks', () => {
  it('1000 random masks: locked roles keep both hex exactly, free roles are regenerated, reports stay truthful', () => {
    const r = rngOf(4242);
    let freeTotal = 0;
    let freeChanged = 0;
    let strictPairs = 0;
    let strictOk = 0;
    let fixedPairs = 0;
    let fixedFailing = 0;
    for (let i = 0; i < 1000; i++) {
      const harmony = HARMONIES[Math.floor(r() * HARMONIES.length)] as H;
      const s0 = Math.floor(r() * 2 ** 32);
      const s1 = Math.floor(r() * 2 ** 32);
      const mask = Math.floor(r() * 128);
      const prev = generate({ harmony, seed: s0, locks: 0 });
      const g = generate({ harmony, seed: s1, locks: mask, previous: theme(prev) });
      for (const role of ROLES) {
        if (isLocked(mask, role)) {
          expect(g.light[role]).toBe(prev.light[role]);
          expect(g.dark[role]).toBe(prev.dark[role]);
        } else {
          freeTotal++;
          if (g.light[role] !== prev.light[role] || g.dark[role] !== prev.dark[role]) freeChanged++;
        }
      }
      for (const m of MODES) {
        const pal = g[m];
        for (const spec of PAIRS) {
          const rep = g.report[m].find((x) => x.id === spec.id) as PairReport;
          const ratio = ratioOf(pal[spec.fg], pal[spec.bg]);
          expect(rep.ratio).toBe(ratio);
          expect(rep.ok).toBe(ratio >= rep.target);
          expect(rep.touchesFixed).toBe(isLocked(mask, spec.fg) || isLocked(mask, spec.bg));
          if (!spec.informational && rep.touchesFixed) {
            fixedPairs++;
            if (!rep.ok) fixedFailing++;
          }
          // Free foreground against a locked background: the report must be explained by what black/white can reach.
          if (!isLocked(mask, spec.fg) && isLocked(mask, spec.bg)) {
            const others = PAIRS.filter((p) => p.fg === spec.fg);
            if (others.every((p) => isLocked(mask, p.bg) || others.length === 1)) {
              const top = spec.ladder[0] as number;
              if (bestExtreme(pal[spec.bg]) >= top && others.length === 1) expect(ratio).toBeGreaterThanOrEqual(top);
            }
          }
          // Pair whose members and the fg's other partners are all free: strict target.
          const partnersFree = PAIRS.filter((p) => p.fg === spec.fg).every((p) => !isLocked(mask, p.bg));
          if (!isLocked(mask, spec.fg) && partnersFree && !isLocked(mask, spec.bg)) {
            strictPairs++;
            const top = spec.ladder[0] as number;
            if (rep.ok && rep.target === top) strictOk++;
            else if (!rep.ok) expect(rep.ok).toBe(false);
          }
        }
      }
    }
    console.log(
      `J2 locks: free roles changed with a new seed ${freeChanged}/${freeTotal} (${((100 * freeChanged) / freeTotal).toFixed(2)} %); ` +
        `strict free pairs at first target ${strictOk}/${strictPairs}; pairs touching a locked role failing ${fixedFailing}/${fixedPairs}`,
    );
    expect(freeChanged / freeTotal).toBeGreaterThan(0.95);
    expect(strictOk).toBe(strictPairs);
  });

  it('locking with the colours generated by the same seed changes nothing (locks do not shift the draws)', () => {
    const r = rngOf(31337);
    for (let i = 0; i < 300; i++) {
      const harmony = HARMONIES[Math.floor(r() * HARMONIES.length)] as H;
      const seed = Math.floor(r() * 2 ** 32);
      const mask = Math.floor(r() * 128) & ~0b0001000; // accent excluded, see the next test
      const free = generate({ harmony, seed, locks: 0 });
      const locked = generate({ harmony, seed, locks: mask, previous: theme(free) });
      expect(JSON.stringify(locked.light)).toBe(JSON.stringify(free.light));
      expect(JSON.stringify(locked.dark)).toBe(JSON.stringify(free.dark));
    }
    const all = generate({ harmony: 'tetrad', seed: 9, locks: 0 });
    const same = generate({ harmony: 'tetrad', seed: 123456, locks: LOCK_ALL, previous: theme(all) });
    expect(JSON.stringify(theme(same))).toBe(JSON.stringify(theme(all)));
  });

  it('locking the accent keeps it exactly; the others derive from the locked (post-ensure) accent, so they may differ', () => {
    const r = rngOf(8);
    for (let i = 0; i < 200; i++) {
      const seed = Math.floor(r() * 2 ** 32);
      const free = generate({ harmony: 'triad', seed, locks: 0 });
      const g = generate({ harmony: 'triad', seed, locks: 0b0001000, previous: theme(free) });
      expect(g.light.accent).toBe(free.light.accent);
      expect(g.dark.accent).toBe(free.dark.accent);
    }
  });

  it('a lock bit without a valid previous hex is ignored (the role stays free)', () => {
    const free = generate({ harmony: 'triad', seed: 5, locks: 0 });
    expect(JSON.stringify(generate({ harmony: 'triad', seed: 5, locks: LOCK_ALL }))).toBe(JSON.stringify(free));
    const bad = { light: { ...free.light, accent: 'nope' }, dark: free.dark };
    const g = generate({ harmony: 'triad', seed: 5, locks: 0b0001000, previous: bad });
    expect(g.light.accent).toBe(free.light.accent);
    expect(g.report.light.find((x) => x.id === 'accent-fond')?.touchesFixed).toBe(false);
  });

  it('both members locked and failing: colours untouched, pair reported failing, never silently changed', () => {
    const free = generate({ harmony: 'complementary', seed: 77, locks: 0 });
    const prev: ThemeColors = {
      light: { ...free.light, fond: '#808080', texte: '#8C8C8C' },
      dark: { ...free.dark, fond: '#808080', texte: '#8C8C8C' },
    };
    const mask = 0b0000101;
    const g = generate({ harmony: 'complementary', seed: 1, locks: mask, previous: prev });
    for (const m of MODES) {
      expect(g[m].fond).toBe('#808080');
      expect(g[m].texte).toBe('#8C8C8C');
      const rep = g.report[m].find((x) => x.id === 'texte-fond') as PairReport;
      expect(rep.ok).toBe(false);
      expect(rep.touchesFixed).toBe(true);
      expect(rep.ratio).toBeLessThan(2);
    }
  });

  it('locked fond of mid luminance: 7 is impossible, texte falls back to 4.5 (light); dark conflict is reported honestly', () => {
    const free = generate({ harmony: 'triad', seed: 3, locks: 0 });
    const prev: ThemeColors = { light: { ...free.light, fond: '#808080' }, dark: { ...free.dark, fond: '#808080' } };
    const g = generate({ harmony: 'triad', seed: 4, locks: 0b0000001, previous: prev });
    expect(bestExtreme('#808080')).toBeLessThan(7);
    const rep = g.report.light.find((x) => x.id === 'texte-fond') as PairReport;
    expect(rep.ok).toBe(true);
    expect(rep.target).toBe(4.5);
    expect(ratioOf(g.light.texte, '#808080')).toBeGreaterThanOrEqual(4.5);
    for (const m of MODES) expect(g[m].fond).toBe('#808080');
    // dark: surface stays dark while the locked fond is mid grey, no text colour serves both: honest report
    const darkReps = g.report.dark.filter((x) => x.fg === 'texte');
    for (const d of darkReps) expect(d.ok).toBe(ratioOf(g.dark.texte, g.dark[d.bg]) >= d.target);
  });

  it('locked texte of mid luminance: the free fond/surface move to keep texte readable, texte untouched', () => {
    const free = generate({ harmony: 'triad', seed: 3, locks: 0 });
    const prev: ThemeColors = { light: { ...free.light, texte: '#595959' }, dark: { ...free.dark, texte: '#B0B0B0' } };
    const g = generate({ harmony: 'triad', seed: 3, locks: 0b0000100, previous: prev });
    expect(g.light.texte).toBe('#595959');
    expect(g.dark.texte).toBe('#B0B0B0');
    expect(ratioOf('#595959', g.light.fond)).toBeGreaterThanOrEqual(7);
    expect(ratioOf('#B0B0B0', g.dark.fond)).toBeGreaterThanOrEqual(7);
  });

  it('a locked accent drives the derivation of the free roles (hue) and ignores a typed base', () => {
    const free = generate({ harmony: 'complementary', seed: 12, locks: 0 });
    const g = generate({ harmony: 'complementary', seed: 99, locks: 0b0001000, previous: theme(free), base: '#FF0000' });
    expect(g.light.accent).toBe(free.light.accent);
    expect(g.dark.accent).toBe(free.dark.accent);
    const g2 = generate({ harmony: 'complementary', seed: 99, locks: 0b0001000, previous: theme(free) });
    expect(JSON.stringify(g)).toBe(JSON.stringify(g2));
  });

  it('plan(): ensure() is actually needed (share of palettes where it moves a role, printed; separate() counted apart)', () => {
    let moved = 0;
    let total = 0;
    let lightTotal = 0;
    let lightAccent = 0;
    let lightAny = 0;
    let separated = 0;
    for (const h of HARMONIES) {
      for (const seed of seedList(1000, 5)) {
        const input = { harmony: h, seed, locks: 0 };
        const raw = plan(input);
        for (const m of MODES) {
          const none = new Set<Role>();
          const ens = ensure(raw[m], none);
          total++;
          if (ROLES.some((role: Role) => raw[m][role] !== ens[role])) moved++;
          if (m === 'light') {
            lightTotal++;
            if (raw.light.accent !== ens.accent) lightAccent++;
            if (ROLES.some((role: Role) => raw.light[role] !== ens[role])) lightAny++;
          }
          if (separate(ens, none, m, h === 'monochrome').moved.length > 0) separated++;
        }
      }
    }
    const pct = (n: number, d: number): string => ((100 * n) / d).toFixed(2);
    console.log(
      `J2b ensure: moved at least one role in ${moved}/${total} palettes (${pct(moved, total)} %); ` +
        `light accent moved in ${lightAccent}/${lightTotal} (${pct(lightAccent, lightTotal)} %), any light role in ${lightAny}/${lightTotal} (${pct(lightAny, lightTotal)} %); ` +
        `separate() shifted a role in ${separated}/${total} (${pct(separated, total)} %)`,
    );
    expect(total).toBe(12000);
  });
});
